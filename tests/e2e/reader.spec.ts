test('offline local note recovery and a real concurrent server revision show three-way comparison before CAS save', async ({ page }) => {
  const fixture = await openActual(page, 'nativeconflict')
  await selectRepeat(page, fixture)
  await page.getByRole('button', { name: '为当前选文记笔记', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: '笔记', exact: true })
  await dialog.getByRole('button', { name: '用当前选文新建笔记', exact: true }).click()
  await dialog.getByLabel('笔记正文').fill('原基准笔记')
  const created = page.waitForResponse(value => value.request().method() === 'POST' && value.url().endsWith('/api/v1/notes'))
  await dialog.getByRole('button', { name: '保存笔记到服务端', exact: true }).click()
  const baseRef = await (await created).json()
  await expect(dialog.getByText('笔记已保存到服务端', { exact: true })).toBeVisible()
  const base: Note = (await page.request.get('/api/v1/notes').then(value => value.json())).items.find((item: Note) => item.id === baseRef.id)
  await dialog.getByLabel('笔记正文').fill('本页离线编辑，必须保留')
  await expect(dialog.getByText('本机草稿已保留；尚未同步为服务端笔记。')).toBeVisible()
  await page.route('**/api/v1/notes**', route => route.abort('internetdisconnected'))
  await page.route(`**/api/v1/objects/${base.id}/current`, route => route.abort('internetdisconnected'))
  await page.reload()
  await expect(page.locator('.real-reader > h1')).toBeVisible()
  await page.getByRole('button', { name: '查看笔记', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '笔记', exact: true })
  await dialog.getByRole('button', { name: `恢复本机笔记草稿 ${base.id}`, exact: true }).click()
  await expect(dialog.getByLabel('笔记正文')).toHaveValue('本页离线编辑，必须保留')
  await expect(dialog.getByRole('alert').first()).toBeVisible()
  await page.unroute('**/api/v1/notes**')
  await page.unroute(`**/api/v1/objects/${base.id}/current`)
  const changed = await page.evaluate(async ({ base, baseRef }) => {
    const auth = await fetch('/api/v1/session').then(value => value.json())
    const response = await fetch(`/api/v1/notes/${base.id}`, { method: 'PATCH', headers: { 'Content-Type': 'application/json', 'X-CSRF-Token': auth.csrf_token, 'Idempotency-Key': crypto.randomUUID(), 'If-Match': `"${baseRef.sha256}"` }, body: JSON.stringify({ ...base, revision: 2, markdown: '另一写入者的服务端笔记' }) })
    return { status: response.status, ref: await response.json() }
  }, { base, baseRef })
  expect(changed.status).toBe(200)
  const rejected = page.waitForResponse(value => value.request().method() === 'PATCH' && value.url().endsWith(`/api/v1/notes/${base.id}`))
  await dialog.getByRole('button', { name: '保存笔记到服务端', exact: true }).click()
  expect((await rejected).status()).toBe(412)
  await expect(dialog.getByRole('heading', { name: '笔记版本冲突', exact: true })).toBeVisible()
  const comparison = dialog.locator('.note-conflict')
  await expect(comparison).toContainText('原基准笔记')
  await expect(comparison).toContainText('本页离线编辑，必须保留')
  await expect(comparison).toContainText('另一写入者的服务端笔记')
  await dialog.getByRole('button', { name: '保留本地内容并采用新基准', exact: true }).click()
  await dialog.getByRole('button', { name: '保存笔记到服务端', exact: true }).click()
  await expect(dialog.getByText('笔记已保存到服务端', { exact: true })).toBeVisible()
  await expect(dialog.locator('.note-identity')).toContainText('修订 3')
  const actual: Note = (await page.request.get('/api/v1/notes').then(value => value.json())).items.find((item: Note) => item.id === base.id)
  expect(actual.markdown).toBe('本页离线编辑，必须保留')
  expect(actual.anchor).toEqual(base.anchor)
})

