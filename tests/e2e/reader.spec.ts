test('second repeated rendered selection preserves exact source codepoints, saves note, edits and soft deletes', async ({ page }) => {
  const fixture = await openActual(page, 'nativenotes')
  await selectRepeat(page, fixture)
  await page.getByRole('button', { name: '为当前选文记笔记', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '笔记', exact: true })
  await dialog.getByRole('button', { name: '用当前选文新建笔记', exact: true }).click()
  await dialog.getByLabel('笔记正文').fill('真实笔记 🧠 中文 café é')
  const response = page.waitForResponse(value => value.request().method() === 'POST' && value.url().endsWith('/api/v1/notes'))
  await dialog.getByRole('button', { name: '保存笔记到服务端', exact: true }).click()
  expect((await response).status()).toBe(201)
  await expect(dialog.getByText('笔记已保存到服务端', { exact: true })).toBeVisible()
  const ref = await (await response).json()
  const note: Note = (await page.request.get('/api/v1/notes').then(value => value.json())).items.find((item: Note) => item.id === ref.id)
  const source = fixture.bodies[fixture.blocks[0].id]
  const offset = source.lastIndexOf('重复句子用于选择定位。')
  expect(note.anchor.start_codepoint).toBe(Array.from(source.slice(0, offset)).length)
  expect(note.anchor.end_codepoint - note.anchor.start_codepoint).toBe(Array.from(note.anchor.exact_quote).length)
  expect(note.anchor.ref).toEqual(fixture.blocks[0])
  await dialog.getByLabel('笔记正文').fill('编辑后仍绑定第二次重复选文')
  await dialog.getByRole('button', { name: '保存笔记到服务端', exact: true }).click()
  await expect(dialog.getByText('笔记已保存到服务端', { exact: true })).toBeVisible()
  await expect(dialog.locator('.note-identity')).toContainText('修订 2')
  await dialog.getByRole('button', { name: '删除此笔记', exact: true }).click()
  await dialog.getByRole('button', { name: '确认软删除笔记', exact: true }).click()
  await expect(dialog.getByText('笔记已从当前视图删除；历史引用保留。')).toBeVisible()
  expect((await page.request.get('/api/v1/notes').then(value => value.json())).items.some((item: Note) => item.id === ref.id)).toBe(false)
  const revisions = await page.request.get(`/api/v1/objects/${ref.id}/revisions`).then(value => value.json())
  expect(revisions.items.length).toBeGreaterThanOrEqual(2)
})


