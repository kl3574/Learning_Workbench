  const fixture = originalReaderPackage(prefix)
  const { dialog } = await importReaderPackage(page, fixture)
  await dialog.getByRole('button', { name: '打开已导入课程', exact: true }).click()
  await page.getByRole('button', { name: '继续阅读 →', exact: true }).click()
